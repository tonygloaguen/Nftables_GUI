from __future__ import annotations

import json
import re
from dataclasses import dataclass

from nft_gui.errors import NftError
from nft_gui.executor.policy import prepare_source
from nft_gui.models import Chain, Counter, Expr, Map, Quota, Rule, Ruleset, Set, Table
from nft_gui.parser.syntax import object_elements, rule_expressions


@dataclass(frozen=True)
class Token:
    text: str
    start: int
    end: int


TOKEN = re.compile(r'#[^\n]*|"(?:\\.|[^"\\])*"|\n|[{};]|[^\s{};#"]+')


def tokens(source: str) -> list[Token]:
    return [Token(m[0], m.start(), m.end()) for m in TOKEN.finditer(source)
            if not m[0].startswith("#")]


def _name(token: str) -> str:
    if token.startswith('"'):
        result = json.loads(token)
        if not isinstance(result, str):
            raise ValueError("Expected a name")
        return result
    return token


def _chunks(items: list[Token]) -> list[list[Token]]:
    chunks: list[list[Token]] = []
    current: list[Token] = []
    depth = 0
    for token in items:
        if token.text in {";", "\n"} and depth == 0:
            if current:
                chunks.append(current)
                current = []
            continue
        current.append(token)
        if token.text == "{":
            depth += 1
        elif token.text == "}":
            depth -= 1
            if depth < 0:
                raise ValueError("Unbalanced braces")
            if depth == 0 and current[0].text in {"table", "chain", "set", "map", "counter", "quota"}:
                chunks.append(current)
                current = []
    if depth:
        raise ValueError("Unbalanced braces")
    if current:
        chunks.append(current)
    return chunks


def _rule(source: str, items: list[Token], family: str, table: str, chain: str) -> Rule:
    raw = source[items[0].start:items[-1].end]
    try:
        statements, comment = rule_expressions(raw)
        return Rule.model_validate({"family": family, "table": table, "chain": chain,
                                    "expr": statements, "comment": comment})
    except (NftError, ValueError, TypeError, IndexError):
        return Rule.model_validate({"family": family, "table": table, "chain": chain,
                                    "expr": [Expr(raw_nft=raw)]})


def from_nft_text(source: str) -> Ruleset:
    """Conservative code -> IR conversion; never pretend to fully parse nft syntax.

    Comments/formatting are retained by keeping the complete source whenever a
    construct is not mapped. A structurally mapped rule may itself be opaque.
    Validation belongs to NftExecutor, not this editor convenience parser.
    """
    original_source = source
    try:
        prepare_source(source)
        generated_header = "# Generated by nft-gui: complete ruleset replacement\n"
        if source.startswith(generated_header):
            source = source[len(generated_header):]
        # Source comments carry user information. Keep them exactly in code mode.
        if any(m[0].startswith("#") for m in TOKEN.finditer(source)):
            return Ruleset(raw_nft=original_source)
        ruleset = Ruleset()
        for chunk in _chunks(tokens(source)):
            words = [t.text for t in chunk]
            if words == ["flush", "ruleset"]:
                continue
            if words[:2] == ["add", "rule"] and len(words) >= 6:
                ruleset.objects.append(_rule(source, chunk[5:], words[2], _name(words[3]), _name(words[4])))
                continue
            if len(words) < 5 or words[0] != "table" or words[3] != "{" or words[-1] != "}":
                return Ruleset(raw_nft=original_source)
            family, table_name = words[1], _name(words[2])
            table = Table.model_validate({"family": family, "name": table_name})
            ruleset.objects.append(table)
            for member in _chunks(chunk[4:-1]):
                w = [t.text for t in member]
                if w[0] == "comment" and len(w) == 2:
                    table.comment = _name(w[1])
                    continue
                if len(w) < 4 or w[2] != "{" or w[-1] != "}":
                    return Ruleset(raw_nft=original_source)
                name = _name(w[1])
                attrs: dict[str, object] = {"family": family, "table": table_name, "name": name}
                properties = _chunks(member[3:-1])
                if w[0] == "chain":
                    rule_chunks: list[list[Token]] = []
                    for prop in properties:
                        p = [t.text for t in prop]
                        if p[:1] == ["type"]:
                            if len(p) >= 8 and p[4] == "device":
                                attrs["dev"] = _name(p[5])
                                p = p[:4] + p[6:]
                            if len(p) < 6 or p[2] != "hook" or p[4] != "priority":
                                return Ruleset(raw_nft=original_source)
                            priority = " ".join(p[5:])
                            attrs.update(type=p[1], hook=p[3], prio=int(priority) if re.fullmatch(r"-?\d+", priority) else priority)
                        elif p[0] in {"policy", "comment"} and len(p) == 2:
                            attrs[p[0]] = _name(p[1])
                        else:
                            rule_chunks.append(prop)
                    ruleset.objects.append(Chain.model_validate(attrs))
                    ruleset.objects.extend(_rule(source, r, family, table_name, name) for r in rule_chunks)
                elif w[0] in {"set", "map"}:
                    for prop in properties:
                        p = [t.text for t in prop]
                        if p[0] == "type":
                            dtype = " ".join(p[1:]).split(" : ")
                            parts = [d.strip().split(" . ") for d in dtype]
                            attrs["type"] = parts[0][0] if len(parts[0]) == 1 else parts[0]
                            if w[0] == "map" and len(parts) == 2:
                                attrs["map"] = parts[1][0] if len(parts[1]) == 1 else parts[1]
                            elif len(parts) != 1:
                                return Ruleset(raw_nft=original_source)
                        elif p[0] == "flags":
                            attrs["flags"] = [f.strip() for f in " ".join(p[1:]).split(",")]
                        elif p[0] in {"timeout", "gc-interval"} and len(p) == 2 and re.fullmatch(r"\d+s", p[1]):
                            attrs[p[0].replace("-", "_")] = int(p[1][:-1])
                        elif p[0] == "size" and len(p) == 2:
                            attrs["size"] = int(p[1])
                        elif p[0] in {"policy", "comment"} and len(p) == 2:
                            attrs[p[0]] = _name(p[1])
                        elif p[:2] == ["elements", "="]:
                            attrs["elem"] = object_elements(source[prop[2].start:prop[-1].end], mapping=w[0] == "map")
                        else:
                            return Ruleset(raw_nft=original_source)
                    ruleset.objects.append((Set if w[0] == "set" else Map).model_validate(attrs))
                elif w[0] in {"counter", "quota"}:
                    for prop in properties:
                        p = [t.text for t in prop]
                        if p[0] == "comment" and len(p) == 2:
                            attrs["comment"] = _name(p[1])
                        elif w[0] == "counter" and len(p) == 4 and p[0] == "packets" and p[2] == "bytes":
                            attrs.update(packets=int(p[1]), bytes=int(p[3]))
                        elif w[0] == "quota":
                            attrs["inv"] = p[0] == "over"
                            p = p[1:] if attrs["inv"] else p
                            if len(p) != 5 or p[1:3] != ["bytes", "used"] or p[4] != "bytes":
                                return Ruleset(raw_nft=original_source)
                            attrs.update(bytes=int(p[0]), used=int(p[3]))
                        else:
                            return Ruleset(raw_nft=original_source)
                    ruleset.objects.append((Counter if w[0] == "counter" else Quota).model_validate(attrs))
                else:
                    # Sets/maps/advanced declarations remain exact, in code mode.
                    return Ruleset(raw_nft=original_source)
        return ruleset
    except (NftError, ValueError, TypeError, IndexError):
        return Ruleset(raw_nft=original_source)
